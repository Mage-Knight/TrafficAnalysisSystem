"""Command-line interface (`ta`)."""

import platform
import sys
from pathlib import Path
from typing import Annotated, NoReturn

import typer

from traffic_analytics import __version__

app = typer.Typer(help="Traffic analytics on UA-DETRAC.", no_args_is_help=True)


@app.callback()
def main() -> None:
    """Traffic analytics CLI."""


@app.command()
def env() -> None:
    """Print Python, torch, CUDA and GPU info."""
    typer.echo(f"traffic-analytics: {__version__}")
    typer.echo(f"Python: {platform.python_version()} ({sys.executable})")
    typer.echo(f"Platform: {platform.platform()}")

    try:
        import torch
    except ImportError:
        typer.echo("torch: not installed (pip install -e '.[ml]')")
        return

    typer.echo(f"torch: {torch.__version__}")
    typer.echo(f"CUDA (build): {torch.version.cuda or 'none'}")
    cuda = torch.cuda.is_available()
    typer.echo(f"CUDA available: {cuda}")
    if not cuda:
        return
    typer.echo(f"cuDNN: {torch.backends.cudnn.version()}")
    count = torch.cuda.device_count()
    typer.echo(f"GPUs: {count}")
    for i in range(count):
        props = torch.cuda.get_device_properties(i)
        mem_gb = props.total_memory / 1024**3
        typer.echo(f"  [{i}] {props.name}, {mem_gb:.1f} GB, compute {props.major}.{props.minor}")


data_app = typer.Typer(help="UA-DETRAC data preparation.", no_args_is_help=True)
app.add_typer(data_app, name="data")

RootOpt = Annotated[Path, typer.Option(help="Unzipped UA-DETRAC download.")]
TrainXmlOpt = Annotated[
    Path | None, typer.Option(help="Train annotation XML folder (default: auto-discover).")
]
TestXmlOpt = Annotated[
    Path | None, typer.Option(help="Test annotation XML folder (default: auto-discover).")
]


def _fail(err: Exception) -> NoReturn:
    typer.echo(f"error: {err}", err=True)
    raise typer.Exit(1)


StatsOpt = Annotated[Path, typer.Option(help="sequence_stats.csv from `ta data stats`.")]
ScenesOpt = Annotated[Path, typer.Option(help="Sequence -> scene map.")]


@data_app.command("split")
def data_split(
    stats: StatsOpt = Path("reports/data/sequence_stats.csv"),
    scenes: ScenesOpt = Path("configs/scenes.yaml"),
    out: Annotated[Path, typer.Option(help="Where to write the split.")] = Path(
        "configs/splits.yaml"
    ),
    seed: int = 0,
    candidates: Annotated[int, typer.Option(help="Seeded scene shuffles to search.")] = 20000,
    min_box_share: Annotated[float, typer.Option(help="Min val share of train boxes.")] = 0.13,
    max_box_share: Annotated[float, typer.Option(help="Max val share of train boxes.")] = 0.20,
    min_class_share: Annotated[
        float, typer.Option(help="Min val share of each class's train boxes.")
    ] = 0.15,
) -> None:
    """Hold out whole train-folder scenes as val (balanced, constrained); test = Test folder."""
    from traffic_analytics.data.detrac import DetracError
    from traffic_analytics.data.splits import (
        load_scenes,
        load_stats,
        make_grouped_split,
        save_splits,
        split_report,
    )

    try:
        rows = load_stats(stats)
        scene_map = load_scenes(scenes)
        splits = make_grouped_split(
            rows, scene_map, seed, candidates, min_box_share, max_box_share, min_class_share
        )
    except DetracError as err:
        _fail(err)
    report = split_report(rows, scene_map, splits)
    header = [
        "UA-DETRAC split by scene; generated by `ta data split`, do not edit by hand.",
        f"inputs: {stats}, {scenes}; seed={seed} candidates={candidates}",
        f"constraints: val box share in [{min_box_share}, {max_box_share}], each class >= "
        f"{min_class_share}, every weather in train and val",
        *report,
    ]
    save_splits(out, splits, header)
    for line in report:
        typer.echo(line)
    typer.echo(f"-> {out}")


@data_app.command("stats")
def data_stats(
    root: RootOpt,
    out: Annotated[Path, typer.Option(help="Output folder for the stats files.")],
    train_xml: TrainXmlOpt = None,
    test_xml: TestXmlOpt = None,
    images: Annotated[
        Path | None, typer.Option(help="Where to look for image folders (default: --root).")
    ] = None,
) -> None:
    """Per-sequence stats (sequence_stats.csv) and a first-frame contact sheet."""
    import csv

    from traffic_analytics.data.detrac import DetracError, parse_sequence
    from traffic_analytics.data.discover import discover
    from traffic_analytics.data.files import atomic_path
    from traffic_analytics.data.stats import (
        STATS_COLUMNS,
        contact_sheet,
        folder_totals,
        group_summary,
        image_size,
        sequence_stats,
    )

    try:
        found = discover(root, train_xml, test_xml, images)
        rows = []
        for folder, xmls in (("train", found.train), ("test", found.test)):
            for name, xml in sorted(xmls.items()):
                size = image_size(found.image_dirs.get(name))
                rows.append(sequence_stats(parse_sequence(xml), folder, size))
                typer.echo(f"[{folder}] {name}")
    except DetracError as err:
        _fail(err)

    out.mkdir(parents=True, exist_ok=True)
    with (
        atomic_path(out / "sequence_stats.csv") as tmp,
        tmp.open("w", newline="", encoding="utf-8") as f,
    ):
        writer = csv.DictWriter(f, fieldnames=STATS_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    contact_sheet(rows, found.image_dirs, out / "contact_sheet.jpg")
    for line in [*found.warnings, *group_summary(rows), *folder_totals(rows)]:
        typer.echo(line)
    typer.echo(f"output: {out / 'sequence_stats.csv'}, {out / 'contact_sheet.jpg'}")


@data_app.command("prepare")
def data_prepare(
    root: RootOpt,
    out: Annotated[Path, typer.Option(help="Output folder.")],
    splits: Annotated[Path, typer.Option(help="Split file from `ta data split`.")] = Path(
        "configs/splits.yaml"
    ),
    scenes: ScenesOpt = Path("configs/scenes.yaml"),
    stride: Annotated[int, typer.Option(help="Keep every Nth frame for detection.")] = 10,
    train_stride: Annotated[int | None, typer.Option(help="Override --stride.")] = None,
    val_stride: Annotated[int | None, typer.Option(help="Override --stride.")] = None,
    test_stride: Annotated[int | None, typer.Option(help="Override --stride.")] = None,
    force: Annotated[bool, typer.Option(help="Delete previous outputs and rebuild.")] = False,
    train_xml: TrainXmlOpt = None,
    test_xml: TestXmlOpt = None,
    images: Annotated[
        Path | None, typer.Option(help="Where to look for image folders (default: --root).")
    ] = None,
) -> None:
    """Export COCO (RF-DETR), YOLO, MOT gt, targets.csv and metadata.csv."""
    from traffic_analytics.data.detrac import DetracError
    from traffic_analytics.data.prepare import format_summary, prepare

    overrides = {"train": train_stride, "val": val_stride, "test": test_stride}
    strides = {k: stride if v is None else v for k, v in overrides.items()}
    try:
        summary = prepare(
            root, out, splits, scenes, strides, force, train_xml, test_xml, images, log=typer.echo
        )
    except DetracError as err:
        _fail(err)
    for line in format_summary(summary):
        typer.echo(line)
